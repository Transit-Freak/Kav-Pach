#!/bin/sh
# מפקח על ריצת המילוי הארוכה. הריצה נמשכת שעות מול שרת חיצוני, ושגיאת
# רשת חולפת אחת מפילה אותה; המצב נשמר אחרי כל צילום, ולכן הפעלה חוזרת
# ממשיכה בדיוק מהנקודה שנעצרה ולא חוזרת לתחילת הדרך.
#
# עוצר מעצמו כשכל הצילומים בטווח עובדו, או אחרי יותר מדי נפילות רצופות
# (סימן לתקלה אמיתית ולא לרעש רשת) — כדי לא להתדפק על שרת שאינו שלנו.
: "${FROM:=20170316}"
: "${TO:=20220115}"
: "${LOG:=/tmp/tf_all.log}"
: "${MAX_FAILS:=40}"
fails=0
while [ "$fails" -lt "$MAX_FAILS" ]; do
  FROM="$FROM" TO="$TO" python3 tools/backfill_tf.py >>"$LOG" 2>&1
  rc=$?
  if [ "$rc" -eq 0 ]; then
    echo "=== הושלם בהצלחה ===" >>"$LOG"
    exit 0
  fi
  fails=$((fails + 1))
  echo "=== נפילה $fails (קוד $rc) — ממשיך מהמצב השמור בעוד 30 שניות ===" >>"$LOG"
  sleep 30
done
echo "=== נעצר אחרי $fails נפילות רצופות ===" >>"$LOG"
exit 1
